#!/usr/bin/env python3
"""Rebrand sweep over the merge result.

For every file the merge touched:
  - lines present in HEAD (unchanged by the merge) are preserved verbatim;
  - added/changed lines are run through the rebrand transform;
  - brand-new files are transformed wholesale.

Run it from inside the merge worktree (or pass --work). The fork repo used as
HEAD ground truth defaults to the worktree itself and can be overridden with
--repo or the UNBLOARCHY_REPO environment variable.
"""
import argparse
import difflib
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import transform


def head_blob_lines(work, path):
    r = subprocess.run(["git", "-C", work, "show", f"HEAD:{path}"], capture_output=True)
    if r.returncode != 0:
        return None
    return r.stdout.decode("utf-8", "surrogateescape").split("\n")


def read_work(work, path):
    with open(os.path.join(work, path), "rb") as f:
        return f.read().decode("utf-8", "surrogateescape").split("\n")


def write_work(work, path, lines):
    with open(os.path.join(work, path), "wb") as f:
        f.write("\n".join(lines).encode("utf-8", "surrogateescape"))


def is_binary(work, path):
    try:
        with open(os.path.join(work, path), "rb") as f:
            return b"\x00" in f.read(8192)
    except OSError:
        return True


SHIM_MARKER = b"# Generated by generate-compat-shims.sh; do not edit."


def is_generated_shim(work, path):
    try:
        with open(os.path.join(work, path), "rb") as f:
            return SHIM_MARKER in f.read(4096)
    except OSError:
        return False


def safe(s):
    return s.encode("utf-8", "replace").decode("utf-8")


def main():
    ap = argparse.ArgumentParser(description="Rebrand sweep over the merge result.")
    ap.add_argument("--work", default=os.getcwd(),
                    help="merge worktree to rewrite (default: current directory)")
    ap.add_argument("--repo", default=None,
                    help="fork repo used as HEAD ground truth (default: same as --work)")
    ap.add_argument("--dry", action="store_true",
                    help="print proposed changes instead of writing them")
    args = ap.parse_args()

    work = os.path.abspath(args.work)
    repo = os.path.abspath(args.repo) if args.repo else work
    transform.configure(repo)
    transform_line = transform.transform_line

    ns = subprocess.run(["git", "-C", work, "diff", "HEAD", "--name-status", "-M"],
                        capture_output=True, text=True).stdout
    changed = 0
    for line in ns.splitlines():
        if not line.strip():
            continue
        parts = line.split("\t")
        st = parts[0]
        if st.startswith(("R", "C")):
            path = parts[2]
        elif st.startswith(("A", "M")):
            path = parts[1]
        else:
            continue  # deletions handled separately
        full = os.path.join(work, path)
        if not os.path.exists(full) or is_binary(work, path) or is_generated_shim(work, path):
            continue
        merge = read_work(work, path)
        head = head_blob_lines(work, path)
        if head is None:
            out = [transform_line(l) for l in merge]
        else:
            sm = difflib.SequenceMatcher(a=head, b=merge, autojunk=False)
            out = []
            for tag, i1, i2, j1, j2 in sm.get_opcodes():
                if tag == "equal":
                    out.extend(head[i1:i2])
                else:
                    out.extend(transform_line(l) for l in merge[j1:j2])
        if out != merge:
            changed += 1
            if args.dry:
                for a, b in zip(merge, out):
                    if a != b:
                        print(f"[{path}]")
                        print(f"  - {safe(a)}")
                        print(f"  + {safe(b)}")
            else:
                write_work(work, path, out)
    verb = "would rewrite" if args.dry else "rewrote"
    print(f"files {verb} by sweep: {changed}")

    # The sweep rewrites content only: it never renames files. Any tracked
    # path that still says "omarchy" but does NOT exist at HEAD (fork ground
    # truth) is a merge-new file the resolver must git mv (or justify keeping),
    # because its rebranded references now point at a name that is not there.
    # bin/omarchy* are generated compat shims and are exempt.
    report_renames(work)


def report_renames(work):
    r = subprocess.run(["git", "-C", work, "ls-files"],
                       capture_output=True, text=True)
    strays = []
    for path in r.stdout.splitlines():
        if "omarchy" not in path.lower() or path.startswith("bin/omarchy"):
            continue
        if subprocess.run(["git", "-C", work, "cat-file", "-e",
                           f"HEAD:{path}"], capture_output=True).returncode != 0:
            strays.append(path)
    if strays:
        print("rename-needed: tracked omarchy paths not present at HEAD "
              "(the sweep does not rename files; git mv them first):")
        for path in strays:
            print(f"  {path}")


if __name__ == "__main__":
    main()
